# Where a scale word multiplied by zero ("sâng bial") can stand, one row
# each, since each reaches the rule's condition by a different path through
# the parser: alone, the whole phrase would be 0; followed by an addend, only
# the addend; and inside a larger number, as its {remainder}, the larger
# number with that place skipped.
_ZERO_MULTIPLIER_POSITIONS = {
    "alone": "{word} bial",
    "followed by an addend": "{word} bial pakhat",
    "inside a larger number": "{above} {word} bial pakhat",
}


@pytest.mark.parametrize("position", sorted(_ZERO_MULTIPLIER_POSITIONS))
def test_no_scale_word_is_multiplied_by_zero(spec, position):
    # Rule 3 on #27: a zero digit is omitted, never said -- 1,990 is "sâng
    # khat za kua leh sawm kua", with nothing for the ones. So "sâng bial"
    # is not a way of writing anything. Output never produces it, since a
    # rule is only reached with a multiplier of at least 1; what keeps it out
    # of input is each rule's condition -- "multiplier > 1" for sawm and za,
    # "multiplier > 0" from sâng up -- and nothing else. Without this test,
    # dropping that condition from any of the seven ladder rules passed both
    # suites, since it changes no rendering and so no vector.
    #
    # Every scale word, in both forms, because the guard is per rule.
    scales = sorted(spec.lexicon["scales"])
    template = _ZERO_MULTIPLIER_POSITIONS[position]
    accepted = []
    for i, scale in enumerate(scales):
        if "{above}" in template and i + 1 == len(scales):
            continue                # nothing larger to sit inside
        above = spec.number_to_text(scales[i + 1]) if i + 1 < len(scales) else ""
        for word in sorted(set(spec.lexicon["scales"][scale].values())):
            text = template.format(word=word, above=above)
            try:
                accepted.append((text, spec.text_to_number(text)))
            except ValueError:
                pass
    assert not accepted, accepted


def test_connector_placement_does_not_survive_tokenisation(spec):
    # The invariant that lets accepted_inputs(every_dimension=True) certify
    # connector placement as its own dimension instead of crossing it with
    # the others (#27, step 1).
    #
    # _tokenize removes connectors before anything matches, so two spellings
    # differing only in where the connector sits reduce to the *same* token
    # list -- there is no later stage left for them to disagree at. Asserted
    # on the token list rather than through text_to_number, because it is
    # the reduction that is orthogonal, not merely the answer: two spellings
    # could agree on the number for unrelated reasons.
    #
    # What this pins is the removal, not its ordering against normalisation.
    # Every connector below is inserted in its canonical lowercase spelling,
    # so a _tokenize that stripped raw connectors *before* normalising would
    # pass this test unchanged. That half is owned by
    # test_connectors_are_normalised_before_being_dropped, which builds a
    # spec whose connector carries a diacritic -- the only test in this
    # suite that fails when the two are swapped, checked by running the
    # whole of it against that mutation.
    #
    # The dimension varied here is (number of gaps, whether the canonical
    # output already carries a connector), and these are all of its values
    # in 0-999 -- one representative each, rather than a handful of numbers
    # that happen to share a shape and so cannot fail independently:
    #
    #     11  -> 1 gap,  no connector    "sâwm pakhat"
    #     21  -> 2 gaps, no connector    "sawm hnih pakhat"
    #     101 -> 2 gaps, has connector   "zâ leh pakhat"
    #     111 -> 3 gaps, has connector   "zâ sâwm leh pakhat"
    #     121 -> 4 gaps, has connector   "zâ sawm hnih leh pakhat"
    #
    # The sixth class, 0 gaps (0-9, "bial"), is left out deliberately: with
    # no gap there is no placement to vary, so the assertion would compare a
    # string to itself.
    #
    # Splitting goes through the spec's declared separators rather than
    # str.split(). The two agree on all 200 Mizo numbers, which is why this
    # is not a fix -- but they already disagree on the other spec in this
    # repo: en.yaml renders 72 numbers as "twenty-one" and friends, where
    # the hyphen is both literal output and a declared separator. The
    # assumption is not fragile in theory, it is already false next door.
    # Joining with a space needs no such care: Unicode White_Space is an
    # effective separator in every spec by the engine's own rule (#46), so
    # a string built with one is always splittable again.
    connector = spec.parse_config["connectors"][0]
    pattern = _separator_pattern(spec.parse_config)
    for n in (11, 21, 101, 111, 121):
        words = generate_vectors._split_words(spec.number_to_text(n), pattern)
        baseline = spec._tokenize(" ".join(words))
        for gaps in generate_vectors._subsets(range(len(words) - 1)):
            spelled = []
            for i, word in enumerate(words):
                spelled.append(word)
                if i in gaps:
                    spelled.append(connector)
            assert spec._tokenize(" ".join(spelled)) == baseline, (n, gaps)


def test_every_dimension_of_variation_parses(spec):
    # The bounded vectors assume parse features compose: each is one stage
    # of a pipeline, so covering them separately covers them together. That
    # assumption is what makes one representative per feature sufficient,
    # and this is where it is actually checked.
    #
    # Each dimension -- template, respelling, connector placement,
    # separator -- varied on its own, plus one fully crossed representative
    # per template. Not the cross product: the test above pins the invariant
    # that makes placement orthogonal to the rest, so crossing them would
    # spend 2^gaps re-checking it. The crossed row is what still catches a
    # stage that only breaks in combination.
    #
    # Placement itself is three points rather than every subset -- none,
    # each gap alone, all of them -- for the same reason one level down.
    # See _placements in generate_vectors.py for which of those three carry
    # detection and which are there to document the accepted set.
    #
    # It lives here rather than in vectors/mizo.json on purpose. A target
    # package cannot import reference/, so this proves the property for the
    # oracle; what protects a target is the composition assumption plus the
    # fact that #20's package is compiled from the same spec.
    #
    # Over one number per shape rather than every number, for the same
    # reason placement is three points rather than every subset: two numbers
    # of the same shape generate the same variant structure with different
    # words in it, and each costs every variant it parses to say so.
    # Per-number correctness is not this test's job and is not weakened --
    # the round-trip tests and the vector-driven ones still visit every
    # number numbers_to_cover lists.
    # See numbers_to_sweep for the dimensions it enumerates.
    swept = generate_vectors.numbers_to_sweep(spec)
    for n in swept:
        candidates = generate_vectors.accepted_inputs(spec, n, every_dimension=True)
        assert candidates, f"n={n} generated no candidates to check"
        for candidate in candidates:
            assert spec.text_to_number(candidate) == n, f"n={n} input={candidate!r}"

    # Vacuity guard, aimed at numbers_to_sweep rather than at a total. The
    # count of candidates used to be the guard, which worked while the sweep
    # visited every number; against a sampled set it would not notice the
    # thing that actually goes wrong, which is a shape class silently
    # dropping out and taking a rule's only representative with it. Ask the
    # engine which rules fire in range and require each to be represented.
    def rules_firing(numbers):
        return {spec._find_rule(n)["name"] for n in numbers}

    every = rules_firing(generate_vectors.numbers_to_cover(spec))
    missing = every - rules_firing(swept)
    assert not missing, f"no number in the sweep reaches {sorted(missing)}"


# --- #65: what the suite visits once the range is too big to walk ---------


@pytest.mark.parametrize("exhaustive_below", [10, 100])
def test_the_sample_loses_no_shape(spec, exhaustive_below):
    # Above EXHAUSTIVE_BELOW, numbers_to_cover keeps one number of each
    # shape, and finds them without walking the range: a number's shape is
    # taken to follow from its rule, its multiplier and its remainder's
    # shape (_shape_representatives). The only way to check that is to walk
    # every number and compare, which needs a range small enough to walk.
    # So sample one that is: lower the exhaustive part to 0-9 or 0-99, and
    # every shape the walk finds must be in the sample. From 0-9, everything
    # above 9 comes out of the recursion; from 0-99, the hundreds do.
    #
    # Capped at 9,999 so it stays cheap once the range grows. The recursion
    # does the same thing at every scale, so the first few are where it can
    # be caught doing it wrong.
    walked = range(spec.supports["min"], min(spec.supports["max"], 9_999) + 1)
    sampled = generate_vectors.numbers_to_cover(spec, exhaustive_below)
    first_of_shape = {}
    for n in walked:
        first_of_shape.setdefault(generate_vectors._shape(spec, n), n)
    found = {generate_vectors._shape(spec, n) for n in sampled if n in walked}
    missing = sorted(n for shape, n in first_of_shape.items() if shape not in found)
    assert not missing, f"the sample has no number shaped like {missing[:10]}"
    # A sample that quietly became the walk would pass the line above.
    assert len(sampled) < len(walked) // 5


def test_the_sample_keeps_the_structural_cases(spec):
    # #27's list of what a sampled table must still show, checked by value.
    # From 100 up, with the threshold lowered: 100 and its neighbours, every
    # multiplier, one digit below 100 with zeros around it (101, 110), and
    # every place filled but one (109, 190 -- 190 is 1990's shape one scale
    # down).
    #
    # Asked of _structural_cases itself, not only of the sample. Most of
    # these are also shapes the sample finds, so a family the function
    # stopped producing could hide behind them: dropping "100 and its
    # neighbours" passed when this only checked the sample.
    cases = generate_vectors._structural_cases(spec, 100)
    expected = {99, 100, 101, 109, 110, 190} | {m * 100 for m in range(1, 10)}
    assert expected <= cases, sorted(expected - cases)
    sampled = set(generate_vectors.numbers_to_cover(spec, 100))
    assert cases | {0, SUPPORTED_MAX} <= sampled, sorted(cases - sampled)

    # And at the real threshold, where the vectors come from: the first
    # scale above it, which holds 1990 itself (#27's hard case for "leh"),
    # and the top of the ladder, whose multiplier runs to 9 rather than to
    # the next scale word.
    cases = generate_vectors._structural_cases(spec, generate_vectors.EXHAUSTIVE_BELOW)
    expected = (
        {999, 1000, 1001, 1010, 1100, 1099, 1909, 1990}
        | {m * 1000 for m in range(1, 10)}
        | {10**9 - 1, 10**9, 10**9 + 1}
        | {m * 10**9 for m in range(1, 10)}
    )
    assert expected <= cases, sorted(expected - cases)
    assert cases <= set(COVERED), sorted(cases - set(COVERED))


