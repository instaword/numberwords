"""Tests for the reference engine (engine.py). Two independent artifacts are
checked against, on purpose, because they prove different things:

- mizo.yaml's examples: block -- 18 pairs a native speaker wrote by hand.
  Independent ground truth: catches a numeral that's simply wrong.
- vectors/mizo.json -- generated from the engine by generate_vectors.py and
  checked into git; it is NOT regenerated by these tests. Catches drift: a
  spec edit whose output changed without a regenerate. It canNOT catch a
  wrong-but-dutifully-regenerated numeral, since it's generated from the
  same engine it's tested against -- that's what the examples: test is for.
  Each entry also carries accepted_inputs: representative spellings
  text_to_number() must accept, one per applicable parse feature (#12). That
  is the half of the contract `text` alone can't state -- a target package
  can match every canonical string and still reject everything a Mizo
  speaker types. See generate_vectors.accepted_inputs() for the rule.

mizo.yaml's core numeral data has been verified by a native Mizo speaker
(see meta.sources). The "leh" connector (parse.connectors) is a separate,
deliberate exception -- not unverified, but a documented team decision to
leave it unresolved (see mizo.yaml's header and its `# Decision (#10)` tag).
Nothing in mizo.yaml is marked TODO(verify) as of #15: parse.aliases was the
last one, and its diacritic part is now handled by parse.strip_diacritics.
These tests check that the engine correctly follows the grammar as written,
not whether the grammar itself is linguistically correct.
"""

